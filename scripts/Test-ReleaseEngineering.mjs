// Checks that a release can be cut from this tree: one version everywhere,
// a changelog entry and release notes for it, the installer's extension
// lists in agreement, a release job that attests the ZIP before publishing
// it, and public text free of AI attribution, em dashes, and claims the
// project has decided not to make.
//
//   node scripts/Test-ReleaseEngineering.mjs
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const failures = [];
// A missing file is a failure to report with the others, not a crash.
const read = (path) => {
  if (existsSync(join(root, path))) return readFileSync(join(root, path), "utf8");
  failures.push(`${path} is missing`);
  return "";
};
const check = (condition, message) => {
  if (!condition) failures.push(message);
};

const version = JSON.parse(read("package.json")).version;
check(/^\d+\.\d+\.\d+$/.test(version), `package.json version ${version} is not X.Y.Z`);
check(/string\(JSON LEANSLIDES_MANIFEST_VERSION GET [^)]*version\)/.test(read("CMakeLists.txt")),
  "CMakeLists.txt does not take the version from package.json");

const changelog = read("CHANGELOG.md");
const firstEntry = changelog.match(/^## \[(\d+\.\d+\.\d+)\] - (\d{4}-\d{2}-\d{2})$/m);
check(firstEntry && firstEntry[1] === version,
  `the first CHANGELOG.md entry is ${firstEntry ? firstEntry[1] : "missing"}, not ${version}`);

const zip = `LeanSlides-v${version}-windows-x64.zip`;
const notesPath = `docs/releases/v${version}.md`;
if (read(notesPath)) {
  const notes = read(notesPath);
  check(notes.includes(zip), `${notesPath} does not name ${zip}`);
  check(notes.includes(`${zip}.sha256`) || notes.includes(".sha256"), `${notesPath} does not mention the .sha256 file`);
}

// The three lists of extensions must agree: what install.ps1 registers, what
// uninstall.ps1 removes, and what the lifecycle test checks.
const extensionList = (text, name) => {
  const match = text.match(new RegExp(`\\$${name}\\s*=\\s*@\\(([^)]*)\\)`));
  return match ? [...match[1].matchAll(/'([^']+)'/g)].map((m) => m[1]).sort().join(" ") : "";
};
const install = read("installer/install.ps1");
const installed = extensionList(install, "Extensions");
check(installed === ".potm .potx .ppsm .ppsx .pptm .pptx", `install.ps1 registers "${installed}"`);
check(extensionList(read("installer/uninstall.ps1"), "Extensions") === installed,
  "uninstall.ps1 and install.ps1 list different extensions");
check(extensionList(read("tests/hosts/Test-WindowsLifecycle.ps1"), "extensions") === installed,
  "the lifecycle test and install.ps1 list different extensions");
const fallback = install.match(/\$FallbackVersion\s*=\s*'([^']+)'/);
check(fallback && fallback[1] === version, `install.ps1 $FallbackVersion is ${fallback ? fallback[1] : "missing"}, not ${version}`);

// The release job publishes only verified, attested files.
const build = read(".github/workflows/build.yml");
check(!build.includes("\t"), "build.yml contains a tab");
check(build.includes("\n  release:"), "build.yml has no release job");
const release = build.includes("\n  release:") ? build.slice(build.indexOf("\n  release:")) : "";
check(release.includes("sha256sum -c"), "the release job does not verify the checksums");
check(release.includes("--notes-file"), "the release job does not publish the release notes");
check(release.includes("--verify-tag"), "the release job does not use --verify-tag");
const attest = release.indexOf("actions/attest-build-provenance@");
const create = release.indexOf("gh release create");
check(attest > 0 && create > attest, "the release job must attest the ZIP before it creates the release");
check(/attest-build-provenance@[0-9a-f]{40}/.test(release), "the attestation action is not pinned to a commit");
for (const name of ["LeanSlides-v${LEANSLIDES_VERSION}-windows-x64.zip", "LeanSlides-v${LEANSLIDES_VERSION}-windows-x64.zip.sha256"]) {
  check(release.includes(name), `the release job does not expect ${name}`);
}

// Wording in every tracked text file.
const tracked = execFileSync("git", ["ls-files", "-z"], { cwd: root, encoding: "utf8" })
  .split("\0")
  .filter((path) => path && /\.(md|mjs|js|cjs|json|ps1|psd1|psm1|cmd|yml|yaml|html|css|txt|cmake|cpp|h|hpp|py|xml|rc|manifest)$|CMakeLists\.txt$|LICENSE$/.test(path))
  .filter((path) => !path.startsWith("third_party/") && !path.startsWith("assets/presets.json") && path !== "package-lock.json");
// "generated by" alone is ordinary licence text (Apache-2.0 section 4).
const attribution = /Co-Authored-By|Claude-Session|claude\.ai|Generated with|Generated by (Claude|AI)|anthropic/i;
// Recorded slide text from public decks is data, not our prose.
const recordedData = /^tests\/.*\.json$/;
const publicText = /^(README\.md|CHANGELOG\.md|SECURITY\.md|docs\/releases\/|site\/|store\/|installer\/README\.md)/;
const marketing = /\b(blazing|seamless(ly)?|cutting-edge|revolutionary|world-class|game-chang\w*|lightning-fast|effortless(ly)?)\b/i;
for (const path of tracked) {
  if (!existsSync(join(root, path))) continue;
  const text = read(path);
  if (path !== "scripts/Test-ReleaseEngineering.mjs") {
    check(!attribution.test(text), `${path} contains AI attribution`);
    check(recordedData.test(path) || !text.includes("—"), `${path} contains an em dash`);
  }
  if (publicText.test(path)) {
    check(!marketing.test(text), `${path} uses a marketing word: ${(text.match(marketing) || [])[0]}`);
    check(!/\bnative (app|application|viewer|reader)\b/i.test(text), `${path} calls LeanSlides native`);
    check(!/\bsecure\b/i.test(text), `${path} says "secure"`);
  }
}

if (failures.length) {
  for (const failure of failures) console.error(`FAIL ${failure}`);
  process.exit(1);
}
console.log(`release engineering checks pass for ${version} (${tracked.length} tracked text files)`);
